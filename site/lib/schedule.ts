// детерминированный «случайный» генератор: расписание стабильно между перезагрузками
const rnd = (seed: number) => { const x = Math.sin(seed) * 10000; return x - Math.floor(x); };
const hash = (s: string) => [...s].reduce((a, c) => (a * 31 + c.charCodeAt(0)) | 0, 7);

function slotsFor(doc: Doctor, clinic: ClinicId, date: Date): number[] {
  const key = doc.id + clinic + date.toDateString();
  if (rnd(hash(key)) < 0.25) return [];
  const out: number[] = [];
  for (let m = 9 * 60; m <= 20 * 60 + 30; m += 30) if (rnd(hash(key + m)) < 0.32) out.push(m);
  return out;
}

export type Window = { date: Date; k: number; m: number; doc: Doctor; clinic: ClinicId };

export function windows(o: { service?: string; doctor?: string; clinic?: ClinicId | ''; now: Date; days?: number }): Window[] {
  const { service, doctor, clinic, now, days = 14 } = o;
  const nowM = now.getHours() * 60 + now.getMinutes();
  const docs = DOCTORS.filter(d => (!service || d.services.includes(service)) && (!doctor || d.id === doctor) && (!clinic || d.clinics.includes(clinic)));
  const res: Window[] = [];
  for (let k = 0; k < days; k++) {
    const date = new Date(now.getFullYear(), now.getMonth(), now.getDate() + k);
    for (const d of docs) for (const c of d.clinics) {
      if (clinic && c !== clinic) continue;
      for (const m of slotsFor(d, c, date)) {
        if (k === 0 && m < nowM + 60) continue;
        res.push({ date, k, m, doc: d, clinic: c });
      }
    }
  }
  return res.sort((a, b) => a.k - b.k || a.m - b.m);
}

const DOW = ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'];
const MON = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

export const dayLabel = (date: Date, k: number) =>
  (k === 0 ? 'Сегодня' : k === 1 ? 'Завтра' : DOW[date.getDay()][0].toUpperCase() + DOW[date.getDay()].slice(1)) + ', ' + date.getDate() + ' ' + MON[date.getMonth()];

export const hm = (m: number) => String(Math.floor(m / 60)).padStart(2, '0') + ':' + String(m % 60).padStart(2, '0');

export const nearLabel = (w?: Window) =>
  w ? (w.k === 0 ? 'сегодня' : w.k === 1 ? 'завтра' : dayLabel(w.date, w.k).toLowerCase()) + ', ' + hm(w.m) : '—';

export const plural = (n: number, a: string, b: string, c: string) =>
  n % 10 === 1 && n % 100 !== 11 ? a : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20) ? b : c;

export const isNight = (d: Date) => d.getHours() >= 21 || d.getHours() < 9;
